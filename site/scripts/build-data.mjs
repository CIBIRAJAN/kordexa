// Regenerates assets/blueprints.js from the CLI's own role blueprints,
// so the website preview can never drift from src/planner.js.
// Usage: node site/scripts/build-data.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const source = fs.readFileSync(path.join(here, "../../src/planner.js"), "utf8");

const start = source.indexOf("const ROLE_BLUEPRINTS = ");
const end = source.indexOf("\n};\n", start);
if (start < 0 || end < 0) throw new Error("Could not locate ROLE_BLUEPRINTS in src/planner.js");

const literal = source.slice(start + "const ROLE_BLUEPRINTS = ".length, end + 2);
const blueprints = new Function(`return (${literal});`)();

const banner = "// Generated by site/scripts/build-data.mjs from src/planner.js. Do not edit by hand.\n";
fs.writeFileSync(
  path.join(here, "../assets/blueprints.js"),
  `${banner}export const BLUEPRINTS = ${JSON.stringify(blueprints)};\n`,
  "utf8"
);

const topicCount = Object.values(blueprints).reduce((sum, role) => sum + role.topics.length, 0);
console.log(`Wrote ${Object.keys(blueprints).length} blueprints, ${topicCount} topics.`);
